import { CanActivateFn, Router, UrlTree } from '@angular/router';
import { inject } from '@angular/core';
import { AuthService } from '../services/auth.service';

/**
 * Functional route guard ensuring that only authenticated sessions can access protected views.
 * Redirects unauthenticated users cleanly to the login view via UrlTree.
 * @returns True if authenticated; otherwise returns a redirect UrlTree to /login.
 */
export const authGuard: CanActivateFn = (): boolean | UrlTree => {
  const authService = inject(AuthService);
  const router = inject(Router);

  if (authService.isAuthenticated()) {
    return true;
  }

  return router.createUrlTree(['/login']);
};
